"""Figures and RESULTS.md from reports/metrics.json and reports/predictions.json.

Run:  python -m surgphase.report
"""
from __future__ import annotations

import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

from .data import COLORS, NICE, ROOT

ORDER = ["frame_only", "causal_lstm", "offline_bilstm"]
SHORT = {"truth": "Surgeon labels", "frame_only": "Single frames", "causal_lstm": "Causal LSTM",
         "offline_bilstm": "BiLSTM"}


def write_report() -> None:
    rep = ROOT / "reports"
    m = json.loads((rep / "metrics.json").read_text())
    pred = json.loads((rep / "predictions.json").read_text())
    (rep / "figures").mkdir(exist_ok=True)

    # 1) phase ribbons for six test videos: best, median and worst by causal-LSTM accuracy
    acc = np.array(m["per_video"]["causal_lstm"])
    vids = np.array(m["videos"]["test"])
    order = np.argsort(-acc)
    picks = [order[0], order[1], order[len(order) // 2 - 1], order[len(order) // 2], order[-2], order[-1]]
    fig, axes = plt.subplots(len(picks), 1, figsize=(11, 1.55 * len(picks)), dpi=140)
    for ax, i in zip(axes, picks):
        v = str(int(vids[i]))
        for row, key in enumerate(["truth", "frame_only", "causal_lstm", "offline_bilstm"]):
            for lab, s, e in pred[v][key]:
                ax.barh(3 - row, (e - s) / 60, left=s / 60, color=COLORS[lab], height=0.9, linewidth=0)
        ax.set_yticks([3, 2, 1, 0], [SHORT[k] for k in ["truth", "frame_only", "causal_lstm", "offline_bilstm"]], fontsize=7)
        ax.set_title(f"Video {v}: causal LSTM accuracy {acc[i]:.1%}", fontsize=8, loc="left")
        ax.tick_params(axis="x", labelsize=7)
        for sp in ax.spines.values():
            sp.set_visible(False)
    axes[-1].set_xlabel("Minutes into the operation", fontsize=8)
    fig.legend(handles=[Patch(color=c, label=n) for c, n in zip(COLORS, NICE)], loc="lower center", ncol=4,
               fontsize=7, frameon=False)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(rep / "figures" / "ribbons.png")
    plt.close(fig)

    # 2) system comparison + per-phase Jaccard + confusion matrix
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.2), dpi=140)
    ax = axes[0]
    xs = np.arange(len(ORDER))
    for off, key, col, lab in [(-0.2, "accuracy", "#0e7490", "Accuracy"), (0.2, "jaccard", "#67e8f9", "Jaccard")]:
        vals = [m["systems"][k][key] for k in ORDER]
        err = [[m["systems"][k][key] - m["systems"][k][key + "_ci95"][0] for k in ORDER],
               [m["systems"][k][key + "_ci95"][1] - m["systems"][k][key] for k in ORDER]]
        ax.bar(xs + off, vals, 0.4, yerr=err, capsize=3, color=col, label=lab)
    ax.set_xticks(xs, ["Single\nframes", "+ causal LSTM\n(live)", "+ BiLSTM\n(whole video)"], fontsize=8)
    ax.set(ylim=(0, 1), title=f"Test videos (n = {m['systems']['causal_lstm']['n_videos']})")
    ax.legend(frameon=False, fontsize=8)
    ax = axes[1]
    w = 0.27
    for j, k in enumerate(ORDER):
        ax.bar(np.arange(len(NICE)) + (j - 1) * w, m["systems"][k]["per_phase"]["jaccard"], w,
               color=["#cbd5e1", "#0e7490", "#164e63"][j], label=SHORT[k])
    ax.set_xticks(range(len(NICE)), [n.replace(" ", "\n") for n in NICE], fontsize=6.5)
    ax.set(ylim=(0, 1), title="Jaccard by phase")
    ax.legend(frameon=False, fontsize=8)
    ax = axes[2]
    cm = np.array(m["confusion_causal_lstm"], float)
    norm = cm / np.maximum(cm.sum(1, keepdims=True), 1)
    ax.imshow(norm, cmap="GnBu", vmin=0, vmax=1)
    for i in range(len(NICE)):
        for j in range(len(NICE)):
            if norm[i, j] >= 0.005:
                ax.text(j, i, f"{norm[i, j]:.2f}", ha="center", va="center", fontsize=6.5,
                        color="white" if norm[i, j] > 0.6 else "black")
    short = ["Prep", "Calot", "Clip", "Dissect", "Pack", "Clean", "Retract"]
    ax.set_xticks(range(7), short, fontsize=7, rotation=30)
    ax.set_yticks(range(7), short, fontsize=7)
    ax.set(xlabel="Predicted", ylabel="Surgeon label", title="Causal LSTM: where seconds go")
    for a in axes[:2]:
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(rep / "figures" / "results.png")
    plt.close(fig)

    v = m["videos"]
    L = ["# Results", "", "Generated by `python -m surgphase.train` from `reports/metrics.json`.", "",
         f"Cholec80 subset: {len(v['train'])} training, {len(v['val'])} validation and {len(v['test'])} test videos "
         f"({m['frames']:,} frames at 1 fps). Metrics are computed per video and averaged; 95% CIs by "
         "bootstrap over test videos.", "",
         "| System | Accuracy (mean, SD) | 95% CI | Precision | Recall | Jaccard | 95% CI |", "|---|---|---|---|---|---|---|"]
    for k in ORDER:
        s = m["systems"][k]
        L.append(f"| {s['label']} | {s['accuracy']:.3f} ({s['accuracy_sd']:.3f}) | {s['accuracy_ci95'][0]:.3f} to "
                 f"{s['accuracy_ci95'][1]:.3f} | {s['precision']:.3f} | {s['recall']:.3f} | {s['jaccard']:.3f} | "
                 f"{s['jaccard_ci95'][0]:.3f} to {s['jaccard_ci95'][1]:.3f} |")
    fmt = lambda p: "<0.0001" if p < 1e-4 else f"{p:.4f}"
    L += ["", f"Paired permutation tests on per-video accuracy: causal LSTM vs single frames p = {fmt(m['p_lstm_vs_frame'])}; "
              f"BiLSTM vs causal LSTM p = {fmt(m['p_bilstm_vs_lstm'])}.", "",
          "## Per phase (causal LSTM)", "", "| Phase | Share of test time | Precision | Recall | Jaccard |", "|---|---|---|---|---|"]
    tot = sum(m["phase_seconds_test"])
    pp = m["systems"]["causal_lstm"]["per_phase"]
    for i, n in enumerate(NICE):
        L.append(f"| {n} | {m['phase_seconds_test'][i] / tot:.1%} | {pp['precision'][i]:.3f} | {pp['recall'][i]:.3f} | {pp['jaccard'][i]:.3f} |")
    L += ["", "## Videos used", "", f"Training: {v['train']}", "", f"Validation: {v['val']}", "", f"Test: {v['test']}"]
    (rep / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write_report()
